import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const parser=createRequire(import.meta.url)('@babel/parser');
const file='src/app/(dashboard)/admin/rate-master/create/page.jsx';
const source=fs.readFileSync(file,'utf8'),ast=parser.parse(source,{sourceType:'module',plugins:['jsx']});
const component=ast.program.body.find(n=>n.type==='ExportDefaultDeclaration').declaration;
const node=component.body.body.flatMap(n=>n.declarations || []).find(n=>n.id.name==='handleBackToList').init;
let destination;
new Function('router','return '+source.slice(node.start,node.end))({push:path=>destination=path})();
assert.equal(destination,'/admin/rate-master/list');
const root=fs.readFileSync('src/app/(dashboard)/admin/rate-master/page.jsx','utf8');
new Function('redirect',root.replace(/^import .*;\r?\n/gm,'').replace('export default function','function')+'\nRateMasterPage();')(path=>destination=path);
assert.equal(destination,'/admin/rate-master/list');
const rates=fs.readFileSync('src/app/(dashboard)/admin/rate-master/rates/[id]/page.jsx','utf8');
parser.parse(rates,{sourceType:'module',plugins:['jsx']});
assert(rates.includes("router.push('/admin/rate-master/list')"));
assert(rates.includes('locationRates: updatedRates'),'Alternate slab editor retains IDs, history flags and metadata');
console.log('PASS: actual create Back handler navigates to list, root redirects to the same list, rate details provides list navigation, and inline edit retains slab metadata.');
