import assert from 'node:assert/strict';
import {initialApproval,submissionUpdate,reviewUpdate,STALE_PROPOSAL} from '../src/lib/masterApprovalPolicy.mjs';
const maker={id:'111',type:'company'},checker={id:'222',type:'user'};
const initial=initialApproval(maker,new Date(0),'new-1');
assert.equal(initial.approvalStatus,'Pending');
assert.throws(()=>reviewUpdate(initial,maker,'approve','new-1'),/own submission/);
assert.throws(()=>reviewUpdate(initial,maker,'reject','new-1','no'),/own submission/);
assert.throws(()=>reviewUpdate(initial,checker,'reject','new-1',''),/reason/);
assert.throws(()=>reviewUpdate(initial,checker,'approve','stale'),e=>e.message===STALE_PROPOSAL);
assert.equal(reviewUpdate(initial,checker,'approve','new-1').$set.approvalStatus,'Approved');
const live={...initial,approvalStatus:'Approved',approvalVersion:2,bankName:'Old',emailId:'old@example.com'};
const proposal=submissionUpdate(live,{bankName:'New',emailId:'new@example.com',approvalStatus:'Approved',approvedBy:maker},maker,'supplier',new Date(1),'change-1');
assert.equal(proposal.$set.bankName,undefined);
assert.equal(proposal.$set.emailId,undefined);
assert.equal(proposal.$set.pendingChange.data.emailId,'new@example.com');
assert.equal(proposal.$set.pendingChange.data.bankName,'New');
assert.equal(proposal.$set.approvedBy,undefined);
const pending={...live,pendingChange:proposal.$set.pendingChange};
assert.throws(()=>submissionUpdate(pending,{bankName:'Other'},checker,'supplier'),/Another maker/);
const replacement=submissionUpdate(pending,{bankName:'Corrected'},maker,'supplier',new Date(2),'change-2');
assert.equal(replacement.$push.approvalLog.$each[0].action,'SUPERSEDED');
const rejected=reviewUpdate(pending,checker,'reject','change-1','Verify bank');
assert.equal(rejected.$set.bankName,undefined);
assert.equal(rejected.$set.approvalStatus,undefined);
assert.equal(rejected.$set.lastRejectedProposal.data.bankName,'New');
assert.equal(rejected.$set.pendingChange,null);
const accepted=reviewUpdate(pending,checker,'approve','change-1');
assert.equal(accepted.$set.bankName,'New');
assert.equal(accepted.$inc.approvalVersion,1);
assert.throws(()=>reviewUpdate({...pending,approvalVersion:3},checker,'approve','change-1'),/Refresh/);
assert.equal(submissionUpdate(live,{bankName:'Old'},maker,'supplier').$set.pendingChange,undefined);
const rejectedNew={...initial,approvalStatus:'Rejected'};
assert.equal(submissionUpdate(rejectedNew,{bankName:'Corrected'},maker,'supplier').$set.approvalStatus,'Pending');
const normalizedStaff={...initial,submittedBy:{accountType:'companyUser',accountId:'222'}};
assert.throws(()=>reviewUpdate(normalizedStaff,checker,'approve','new-1'),/own submission/);
console.log('PASS: maker/checker, forged fields, initial approval, resubmission, protected live values, rejection, replacement and stale reviews.');

assert.throws(()=>reviewUpdate({approvalStatus:'Pending'},checker,'approve',undefined),/no complete approval submission/);
