import assert from 'node:assert/strict';
import { makeHarness, plain } from './workflow-role-harness.mjs';
import { syncPurchaseFromLoading } from '../src/lib/purchaseReapproval.mjs';
import { hasReapprovalReview } from '../src/lib/reapprovalReviewVisibility.mjs';
import { advanceForFixedBalance } from '../src/lib/purchasePaymentTerms.mjs';
const h = makeHarness(), { env, fixtures, request } = h;
Object.assign(env, {syncPurchaseFromLoading, advanceForFixedBalance, hasReapprovalReview});
Object.assign(env, h.compile('src/lib/vehicleNegotiationWorkflow.js', ['isVnnReadyForDownstream','getFinalVnnStatus','getVnnListStatus','withVnnDisplayData']));
Object.assign(env, h.compile('src/lib/deletion/linkGraph.js', ['TYPES','resolveDeleteGraph','deletionBlockers']));
Object.assign(env, h.compile('src/lib/reapprovalService.js', ['summarizeApprovedChanges','findDetachedVnnOrderMarkers','findDetachedLoadingOrderMarkers','recordApprovedRevision','captureSourceDependencies','assertSourcesCurrent','withApprovedVnnLocationRemarks','findLatestApprovedVnnForLoading']));
const correction = h.compile('src/app/api/reapproval/[type]/[id]/route.js',['GET','POST']);
const route = h.compile('src/app/api/purchase-panel/route.js',['PUT','PATCH']);
const queue = h.compile('src/app/api/reapproval/queue/route.js',['GET']);
const editor=h.actor('Purchase Panel','edit'), approver=h.actor('Purchase Panel','approve'), viewer=h.actor('Purchase Panel','view');
const purchase = h.document({purchaseNo:'TEST-PUR-1',loadingInfoNo:fixtures.loading.vehicleArrivalNo,vnnNo:fixtures.vnn.vnnNo,panelStatus:'Approved',isDraft:false,approval:{status:'Approved'},orderRows:[{...plain(fixtures.loading.orderRows[0]),rate:100}],header:{branch:h.branch},purchaseDetails:{vendorName:'Vendor',rate:100,amount:500,advance:200},purchaseAmountFromVNN:500,additions:[{amount:15}],deductions:[{amount:5}]});
h.tables.PurchasePanel.push(purchase);
await env.captureSourceDependencies('purchase',purchase,h.tenant);
purchase.approvedSnapshot=plain(purchase);purchase.approvedRevision=1;
const check=(res,status)=>assert.equal(res.status,status,JSON.stringify(res));
const act=(type,id,action)=>correction.POST(request(h.admin,{action,reason:'Correct route'}),{params:Promise.resolve({type,id})});
let preview=await correction.GET(request(h.admin),{params:Promise.resolve({type:'vnn',id:fixtures.vnn._id})});
check(preview,200);assert(!preview.blockers.length,JSON.stringify(preview.blockers));
check(await act('vnn',fixtures.vnn._id,'unlock'),200);
assert.equal(purchase.reapprovalState,'blockedByUpstream');
check(await route.PATCH(request(approver,{id:purchase._id,action:'approve'})),409);
check(await act('vnn',fixtures.vnn._id,'cancel'),200);
assert.equal(purchase.reapprovalState,'none');
// Reapproval without source changes releases the temporary Purchase block.
check(await act('vnn',fixtures.vnn._id,'unlock'),200);
await env.recordApprovedRevision('vnn',fixtures.vnn._id,h.admin);
assert.equal(purchase.reapprovalState,'none');
// Changed source flows through Loading Info to an editor-owned Purchase review.
check(await act('vnn',fixtures.vnn._id,'unlock'),200);
fixtures.vnn.orders[0].weight=7;
fixtures.vnn.reapprovalState='pendingApproval';
await env.recordApprovedRevision('vnn',fixtures.vnn._id,h.admin);
assert.equal(purchase.reapprovalState,'blockedByUpstream');
await env.recordApprovedRevision('loading',fixtures.loading._id,h.admin);
assert.equal(purchase.reapprovalState,'unlocked');
assert.equal(purchase.orderRows[0].weight,7);
assert.equal(purchase.purchaseAmountFromVNN,500,'financial amounts require Purchase editor review');
assert.equal(purchase.additions[0].amount,15);
let tasks=(await queue.GET(request(editor))).records;
assert(tasks.some(item=>item.id===purchase._id&&item.actionable&&item.path===`/admin/Purchase-Panel/${purchase._id}`));
check(await route.PATCH(request(approver,{id:purchase._id,action:'approve'})),409);
check(await route.PUT(request(viewer,{id:purchase._id,saveMode:'draft'})),403);
check(await route.PUT(request(editor,{id:purchase._id,saveMode:'draft'})),200);
check(await route.PUT(request(editor,{id:purchase._id,saveMode:'submit'})),200);
assert.equal(purchase.reapprovalState,'pendingApproval');
check(await route.PATCH(request(approver,{id:purchase._id,action:'reject',remarks:'Review amount'})),200);
assert.equal(purchase.reapprovalState,'unlocked');
check(await route.PUT(request(editor,{id:purchase._id,saveMode:'submit'})),200);
check(await route.PATCH(request(approver,{id:purchase._id,action:'approve'})),200);
assert.equal(purchase.reapprovalState,'none');assert.equal(purchase.approvedRevision,2);
// Purchase is supported, but Advance Payment remains outside this rollout.
const advance=h.document({paymentNo:'TEST-ADV-1',purchaseNo:purchase.purchaseNo,paymentDetails:{paymentStatus:'Pending'}});
h.tables.AdvancePayment.push(advance);
preview=await correction.GET(request(h.admin),{params:Promise.resolve({type:'purchase',id:purchase._id})});
assert(preview.blockers.some(message=>message.includes('Advance Payment')&&message.includes('not included')));
assert(!preview.blockers.some(message=>message.startsWith('Purchase ')&&message.includes('not included')));
check(await act('purchase',purchase._id,'unlock'),409);
assert.equal(advance.reapprovalState,'none');
// Ambiguous legacy row matches keep the Purchase blocked rather than guessing.
const ambiguous=plain(purchase);delete ambiguous.orderRows[0].orderRowId;
const loading=plain(fixtures.loading);loading.orderRows.push({...loading.orderRows[0]});
assert.equal(syncPurchaseFromLoading(loading,ambiguous).ambiguous,true);
console.log('PASS: Purchase-only rollout, upstream block/cancel, Loading sync, editor review/resubmit, rejection and approval, queue ownership, ambiguous links and unchanged Advance blocker.');


h.tables.AdvancePayment.length=0;
check(await correction.POST(request(editor,{action:'requestUnlock',reason:'Correct purchase terms'}),{params:Promise.resolve({type:'purchase',id:purchase._id})}),200);
check(await correction.POST(request(h.users.vnn.approver,{action:'unlock',reason:'Cross-panel attempt'}),{params:Promise.resolve({type:'purchase',id:purchase._id})}),403);
check(await correction.POST(request(approver,{action:'unlock',reason:'Correct purchase terms'}),{params:Promise.resolve({type:'purchase',id:purchase._id})}),200);
assert.equal(purchase.reapprovalState,'unlocked');
check(await act('purchase',purchase._id,'cancel'),200);
assert.equal(purchase.reapprovalState,'none');
const legacy=plain(purchase);legacy.orderRows[0].orderRowId='old-ui-generated-id';
assert.equal(syncPurchaseFromLoading(fixtures.loading,legacy).ambiguous,false);
console.log('PASS: unchanged upstream releases Purchase, panel-specific direct correction unlock/cancel and unique legacy row matching.');
