// Temporary switch only: the existing ICICI submission implementation stays
// intact. Set ICICI_CIB_SKIP_QUEUE_API=false to resume API-backed queues.
export function isIciciQueueApiSkipped(env = process.env) {
  return env.ICICI_CIB_SKIP_QUEUE_API === 'true';
}

export function generateLocalPaymentQueue(kind, payment, user, now = new Date()) {
  const fail = (message) => { throw Object.assign(new Error(message), { status: 409 }); };
  if (payment.isDraft) fail('Submit this payment before generating its queue.');
  if (payment.queueGenerated) fail('Payment queue has already been generated.');
  const status = kind === 'advance' ? payment.paymentDetails?.paymentStatus || payment.status : payment.paymentStatus;
  if (status !== 'Approved') fail('Approve this payment before generating its queue.');
  if (payment.bankIntegration?.provider === 'ICICI_CIB') fail('This payment already has a bank submission. Resolve its bank status before generating another queue.');
  const amount = Number(kind === 'advance' ? payment.paymentDetails?.finalAmount : payment.finalAmount);
  if (!Number.isFinite(amount) || amount <= 0) fail('A payment amount greater than zero is required.');
  payment.queueGenerated = true;
  payment.queueDate = now;
  payment.bankIntegration = {
    provider: 'ERP_QUEUE', bankStatus: 'Generated', message: 'Payment queue generated.',
    events: [...(payment.bankIntegration?.events || []), {
      event: 'QUEUE_GENERATED_API_SKIPPED', bankStatus: 'Generated', at: now,
      message: `Queue generated by ${user.name || user.id || 'authorized user'}${user.id ? ` (${user.id})` : ''}. Amount: ${amount}. No bank submission was made.`,
    }],
  };
  if (kind === 'balance') payment.paymentStatus = 'Queued';
  return { queueGenerated: true, queueDate: now, amount, provider: 'ERP_QUEUE', bankStatus: 'Generated', paymentStatus: kind === 'advance' ? status : payment.paymentStatus };
}
